    /**
     * Atualiza o estado da interface gráfica ao iniciar o servidor remoto.
     *
     * @param message Mensagem a ser exibida como título da janela
     */
    @Override
    public void onStartRemote(String message) {
        setTitle(message); // Define o título da janela com a mensagem recebida
        imgServerRunning.setEnabled(true);
        btStartServer.setEnabled(false);
        GuiUtils.addText(txtServerLog, "Start server", message);

    }
    // Formato de data e hora para exibição no log
    static DateTimeFormatter hfmt = DateTimeFormatter.ofPattern("HH:mm:ss.SSS");

    /**
     * Regista e exibe informações sobre exceções que ocorreram no sistema.
     *
     * @param e A exceção capturada
     * @param title O título ou contexto associado à exceção
     */
    @Override
    public void onException(Exception e, String title) {
        txtTimeLog.setText(LocalTime.now().format(hfmt));
        txtExceptionLog.setForeground(new java.awt.Color(255, 0, 0));
        txtExceptionLog.setText(e.getMessage());
        txtTitleLog.setText(title); // Exibe o título associado à exceção
    }

    /**
     * Adiciona uma mensagem ao log do servidor e alterna para o painel
     * correspondente.
     *
     * @param title O título associado à mensagem
     * @param message O conteúdo da mensagem
     */
    @Override
    public void onMessage(String title, String message) {
        GuiUtils.addText(txtServerLog, title, message);
        tpMain.setSelectedComponent(pnServer);
    }

    /**
     * Atualiza a interface com os detalhes da rede e exibe os nós conectados.
     *
     * @param address Endereço do nó que se conectou
     */
    @Override
    public void onConect(String address) {
        try {
            // Obtém a lista de nós conectados
            List<IremoteP2P> net = myremoteObject.getNetwork();
            String txt = "";

            // Itera sobre os nós conectados e adiciona os seus endereços ao texto
            for (IremoteP2P iremoteP2P : net) {
                txt += iremoteP2P.getAdress() + "\n";
            }
            txtNetwork.setText(txt); // Atualiza a área de texto com os endereços da rede
            tpMain.setSelectedComponent(pnNetwork); // Alterna para o painel de rede
        } catch (RemoteException ex) {
            onException(ex, "On conect");
            Logger.getLogger(NodeP2PGui.class.getName()).log(Level.SEVERE, null, ex);
        }

    }

    /**
     * Atualiza a interface gráfica para refletir as alterações na blockchain.
     *
     * @param b A blockchain atualizada
     */
    @Override
    public void onBlockchainUpdate(BlockChain b) {
        // Executa a atualização na thread da interface gráfica
        SwingUtilities.invokeLater(() -> {
            DefaultListModel model = new DefaultListModel();
            // Adiciona os blocos da blockchain ao modelo em ordem reversa
            for (int i = b.getSize() - 1; i >= 0; i--) {
                model.addElement(b.get(i));
            }
            lstBlockChain.setModel(model);
            lstBlockChain.setSelectedIndex(0); // Seleciona o primeiro bloco
            tpMain.setSelectedComponent(pnBlockchain);
            repaint();
        });
    }

