    private void lstBlockChainValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lstBlockChainValueChanged
        try {
            // Obtém a blockchain do objeto remoto
            BlockChain bc = myremoteObject.getBlockchain();

            // Determina o índice do bloco selecionado
            int index = bc.getSize() - lstBlockChain.getSelectedIndex() - 1;
            if (index < 0 || index >= bc.getSize()) {
                return;
            }

            // Obter o bloco selecionado
            Block selected = bc.get(index);

            // Atualizar a visualização do cabeçalho do bloco
            txtBlockHeader.setText(selected.getHeaderString());
            txtBlockHeader.setCaretPosition(0);

            // Atualizar a visualização das transações do bloco
            txtBlockTransactions.setText(selected.getTransactionsString());
            txtBlockTransactions.setCaretPosition(0);

            // Carregar e exibir a Merkle Tree associada ao bloco selecionado            
            MerkleTree mk = selected.mk;
            merkleGraphics1.setMerkle(mk); // Atualizar a visualização gráfica da Merkle Tree

        } catch (RemoteException ex) {
            onException(ex, "Erro ao obter a blockchain.");
        }
    }//GEN-LAST:event_lstBlockChainValueChanged

