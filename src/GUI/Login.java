    private void btConectarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btConectarActionPerformed

        try {
            // Obtém o endereço do servidor inserido pelo utilizador
            String enderecofornecido = txtendereco.getText().trim();

            // Verifica se o endereço começa com "//" (formato correto)
            if (enderecofornecido.isEmpty() || !enderecofornecido.startsWith("//")) {
                JOptionPane.showMessageDialog(this, "Por favor, insira o endereço completo no formato //IP:PORTA/ObjetoRemoto", "Erro", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Tenta obter o objeto remoto do servidor
            IremoteP2P node = (IremoteP2P) RMI.getRemote(enderecofornecido);

            // Aqui, o cliente envia o seu objeto (nó) para o servidor
            // A ideia é que o servidor adicione este nó à sua rede
            node.addNode(node); // O servidor deve ter este método para adicionar nós à sua rede

            // Agora que estamos conectados, podemos exibir uma mensagem de sucesso
            JOptionPane.showMessageDialog(this, "Conexão bem-sucedida ao servidor: " + enderecofornecido, "Sucesso", JOptionPane.INFORMATION_MESSAGE);

        } catch (Exception ex) {
            // Trata erros de conexão e exibe mensagem de erro
            JOptionPane.showMessageDialog(this, "Erro ao conectar: " + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
            Logger.getLogger(NodeP2PGui.class.getName()).log(Level.SEVERE, null, ex);
        }


    }//GEN-LAST:event_btConectarActionPerformed

    /**
     * Método para obter os nomes de todos os utilizadores com conta criada
     */
    public void getNameUsers() {

        usersname.clear();

        // Define o caminho para a root do projeto
        String projectRootPath = System.getProperty("user.dir");

        // Cria um objeto File que representa a root do projeto
        File projectRoot = new File(projectRootPath);

        // Obtém a lista de ficheiros e diretórios
        File[] files = projectRoot.listFiles();

        if (files != null) {
            for (File file : files) {
                // Verifica se é um ficheiro e se a extensão é .priv
                if (file.isFile() && file.getName().endsWith(".priv")) {
                    usersname.add(file.getName().replace(".priv", ""));
                }
            }
        } else {
            System.out.println("Não foi possível listar os ficheiros.");
        }
    }

