    private void btLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btLoginActionPerformed

        try {
            
            // Obtém o endereço do nó para a comunicação remota
            String endereco = txtendereco.getText().trim();
            IremoteP2P myremoteObject = (IremoteP2P) Naming.lookup(endereco);
            
                      
            User u = new User(txtLoginUser.getText());
            
            // Carrega os dados do utilizador a partir da senha inserida
            u.load(new String(txtLoginPass.getPassword()));
            // Converte a chave pública do utilizador para Base64 e exibe-a na interface
            String pub = Base64.getEncoder().encodeToString(u.getPub().getEncoded());
            txtPublicKey.setText(pub);
            
            
            
            boolean sucessologin = myremoteObject.login(txtLoginUser.getText(), txtLoginPass.getPassword());

            
            // Verifica se o registo foi bem-sucedido
            if (sucessologin) {
                // Informa o sucesso da criação do utilizador
                JOptionPane.showMessageDialog(this, "Login efetuado com sucesso!");
                // Abre a interface principal do sistema com o utilizador autenticado
                new AssetumGUI(u, endereco).setVisible(true);
                setVisible(false);
                
                
            } else {
                // Informa o insucesso do login 
                JOptionPane.showMessageDialog(this, "Erro ao fazer login");
            }
                        
        } catch (Exception ex) {
            // Exibe um erro caso as credenciais estejam incorretas ou ocorram outros problemas
            Logger.getLogger(Login.class.getName()).log(Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }
    }//GEN-LAST:event_btLoginActionPerformed

