    /**
     * Atualiza a interface com os detalhes da rede e exibe os nós conectados.
     *
     * @param address Endereço do nó que se conectou
     */    
    @Override
    public void onConect(String address) {
        try {
            // Obtém a lista de nós conectados
            List<IremoteP2P> net = myremoteObject.getNetwork();
            String txt = "";
            // Itera sobre os nós conectados e adiciona os seus endereços ao texto
            for (IremoteP2P iremoteP2P : net) {
                txt += iremoteP2P.getAdress() + "\n";
            }
        } catch (RemoteException ex) {
            onException(ex, "On conect");
            Logger.getLogger(Login.class.getName()).log(Level.SEVERE, null, ex);
        }

    }

  
