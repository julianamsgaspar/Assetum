    private void btRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btRegisterActionPerformed

        try {

            // Obtém o endereço do nó para a comunicação remota
            String endereco = txtendereco.getText().trim();
            IremoteP2P myremoteObj = (IremoteP2P) Naming.lookup(endereco);

            // Chama o método de registo no servidor remoto
            boolean sucesso = myremoteObj.register(txtRegisterUser.getText(), txtRegisterPass.getPassword());

            // Verifica se o registo foi bem-sucedido
            if (sucesso) {
                // Informa o sucesso da criação do utilizador
                JOptionPane.showMessageDialog(this, "Utilizador criado com sucesso");
            } else {
                // Informa o insucesso da criação do utilizador
                JOptionPane.showMessageDialog(this, "Erro ao criar utilizador");
            }

            // Limpa os campos
            txtRegisterUser.setText("");
            txtRegisterPass.setText("");
            

        } catch (Exception ex) {
            // Exibe um erro caso ocorra um problema ao criar o utilizador
            Logger.getLogger(Login.class.getName()).log(Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }

    }//GEN-LAST:event_btRegisterActionPerformed

