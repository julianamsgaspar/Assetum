    /**
     * Preenche a dropdown de utilizadores com os dados obtidos de um sistema
     * remoto. Este método faz uma chamada remota para obter a lista de
     * utilizadores e preenche a dropdown com os nomes.
     */
    private void preencherDropdown() {
        try {
            // Chama o método remoto para obter a lista de utilizadores
            ArrayList<UtilizadorData> utilizadores = (ArrayList<UtilizadorData>) myremoteObj.getUsers();

            // Cria um DefaultComboBoxModel para preencher a dropdown
            DefaultComboBoxModel<String> model = new DefaultComboBoxModel<>();

            // Adiciona o nome de cada utilizador ao modelo da dropdown
            for (UtilizadorData utilizador : utilizadores) {
                model.addElement(utilizador.getNome()); // Adiciona o nome do utilizador
            }

            // Atualiza o modelo da dropdown com a lista de utilizadores
            dropDownUsers.setModel(model);

        } catch (RemoteException e) {
            // Trata erro de comunicação remota, caso haja algum problema na chamada remota
            e.printStackTrace();
        }
    }

    /**
     * Função que procura transações com o nome no final. Este método procura
     * transações que terminam com o nome especificado e retorna uma lista de
     * transações encontradas.
     *
     * @param transacoes Lista de transações para procurar
     * @param nomeSelecionado Nome a ser procurado no final das transações
     * @return Lista de transações que terminam com o nome especificado
     */
    private List<String> procuracurriculo(List<String> transacoes, String nomeSelecionado) {
        // Lista onde serão armazenadas as transações que atendem ao critério
        List<String> transacoesEncontradas = new ArrayList<>();

        // Procura por transações que terminam com o nomeSelecionado
        for (String transacao : transacoes) {
            // Verifica se a transação termina com o nome especificado
            if (transacao.endsWith(nomeSelecionado)) {
                transacoesEncontradas.add(transacao); // Adiciona à lista de transações encontradas
            }
        }
        // Retorna a lista de transações encontradas
        return transacoesEncontradas;
    }

