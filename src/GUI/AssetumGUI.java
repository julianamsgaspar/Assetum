    private void btCurriculoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btCurriculoActionPerformed

        // Pega o nome selecionado na dropdown
        String nomeSelecionado = (String) dropDownUsers.getSelectedItem();

        try {

            // Chama o método remoto para obter as transações temporárias
            List<String> transacoesTemporarias = myremoteObj.getTransactions();

            // Chama o método remoto para obter as transações da blockchain
            List<String> transacoes = myremoteObj.getBlockchainTransactions();

            // Combina as duas listas de transações
            List<String> todasTransacoes = new ArrayList<>();

            todasTransacoes.addAll(transacoes);

            // Se a lista de transações temporárias tiver menos de 4 eventos, adiciona as transações temporárias
            if (transacoesTemporarias.size() < 4) {
                todasTransacoes.addAll(transacoesTemporarias);
            }

            // Filtra as transações que acabem com o nome selecionado
            List<String> curriculo = procuracurriculo(todasTransacoes, nomeSelecionado);

            // Limpa o conteúdo atual da JTextArea
            txtCurriculo.setText("");

            // Adiciona as transações filtradas na JTextArea
            for (String transacao : curriculo) {
                // Adiciona uma transação de cada vez à JTextArea
                txtCurriculo.append(transacao + "\n");  // "\n" adiciona uma nova linha após cada transação
            }

        } catch (RemoteException e) {
            e.printStackTrace();  // Tratar o erro de comunicação remota
        }


    }//GEN-LAST:event_btCurriculoActionPerformed


